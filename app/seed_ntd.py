def seed_ntd(db):
    from app.models import NtdDocument, NtdClause

    if NtdDocument.query.first():
        return
    for code, title, dtype, cat, year, url in NTD_LIST:
        d = NtdDocument(code=code, title=title, doc_type=dtype, category=cat,
                        year=year, status="не проверен", official_source=url,
                        notes="Статус будет обновлен автоматической проверкой "
                              "актуальности (раздел «База НТД»).")
